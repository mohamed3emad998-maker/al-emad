export function getDict(locale: Locale): Dict {
  return dict[locale] as Dict;
}

/** Content helper: c("hero.title_1") */
export function makeT(content: ContentMap, locale: Locale) {
  /** strict = don't fall back to the other language when this one is intentionally empty */
  return (key: string, strict = false) => {
    const v = content[key];
    if (!v) return "";
    const own = locale === "ar" ? v.ar : v.en;
    if (strict) return own ?? "";
    return own || (locale === "ar" ? v.en : v.ar) || "";
  };
}
