// Generates supabase/seed.sql from supabase/seed-data.json
// Usage: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(root, "supabase", "seed-data.json"), "utf8"));

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) return `array[${v.map(q).join(",")}]::text[]`;
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out = [];
out.push("-- AUTO-GENERATED by scripts/build-seed.mjs from supabase/seed-data.json");
out.push("-- Initial website content. Safe to re-run: it only inserts rows that don't exist yet.\n");

const s = data.settings;
out.push(
  `insert into public.site_settings (id, logo_url, favicon_url, colors, hero, seo, contact, social, sections, nav)
values (1, ${q(s.logo_url)}, ${q(s.favicon_url)}, ${q(s.colors)}, ${q(s.hero)}, ${q(s.seo)}, ${q(s.contact)}, ${q(s.social)}, ${q(s.sections)}, ${q(s.nav)})
on conflict (id) do nothing;\n`
);

out.push("insert into public.content (key, value_ar, value_en) values");
out.push(
  Object.entries(data.content)
    .map(([k, v]) => `  (${q(k)}, ${q(v.ar)}, ${q(v.en)})`)
    .join(",\n") + "\non conflict (key) do nothing;\n"
);

out.push("do $$ begin\nif not exists (select 1 from public.stats) then");
out.push("insert into public.stats (value, suffix, label_ar, label_en, sort_order) values");
out.push(data.stats.map((r) => `  (${q(r.value)}, ${q(r.suffix)}, ${q(r.label_ar)}, ${q(r.label_en)}, ${q(r.sort_order)})`).join(",\n") + ";");
out.push("end if;\nend $$;\n");

out.push("insert into public.services (slug, sort_order, title_ar, title_en, summary_ar, summary_en, details_ar, details_en, image_url, image_alt_ar, image_alt_en) values");
out.push(
  data.services
    .map((r) => `  (${[r.slug, r.sort_order, r.title_ar, r.title_en, r.summary_ar, r.summary_en, r.details_ar, r.details_en, r.image_url, r.image_alt_ar, r.image_alt_en].map(q).join(", ")})`)
    .join(",\n") + "\non conflict (slug) do nothing;\n"
);

out.push("do $$\ndeclare cat uuid;\nbegin\nif not exists (select 1 from public.part_categories) then");
for (const c of data.part_categories) {
  out.push(`  insert into public.part_categories (name_ar, name_en, sort_order) values (${q(c.name_ar)}, ${q(c.name_en)}, ${q(c.sort_order)}) returning id into cat;`);
  for (const p of data.parts.filter((x) => x.category === c.key)) {
    out.push(
      `  insert into public.parts (category_id, name_ar, name_en, description_ar, description_en, image_url, image_alt_ar, image_alt_en, brands, sort_order) values (cat, ${[p.name_ar, p.name_en, p.description_ar, p.description_en, p.image_url, p.image_alt_ar, p.image_alt_en, p.brands, p.sort_order].map(q).join(", ")});`
    );
  }
}
out.push("end if;\nend $$;\n");

out.push("do $$ begin\nif not exists (select 1 from public.gallery_items) then");
out.push("insert into public.gallery_items (category, media_type, url, poster_url, caption_ar, caption_en, sort_order) values");
out.push(
  data.gallery
    .map((g) => `  (${[g.category, g.media_type ?? "image", g.url, g.poster_url ?? null, g.caption_ar, g.caption_en, g.sort_order].map(q).join(", ")})`)
    .join(",\n") + ";"
);
out.push("end if;\nend $$;\n");

out.push("do $$ begin\nif not exists (select 1 from public.testimonials) then");
out.push("insert into public.testimonials (customer_name, car, text_ar, text_en, rating, sort_order) values");
out.push(
  data.testimonials
    .map((t) => `  (${[t.customer_name, t.car, t.text_ar, t.text_en, t.rating, t.sort_order].map(q).join(", ")})`)
    .join(",\n") + ";"
);
out.push("end if;\nend $$;\n");

writeFileSync(join(root, "supabase", "seed.sql"), out.join("\n"), "utf8");
console.log("Wrote supabase/seed.sql");
